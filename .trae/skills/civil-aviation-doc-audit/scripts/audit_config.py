def get_full_subdivision_tree() -> Dict[str, Any]:
    """
    返回完整的分部分项树形结构，用于审核报告中的层级展示。
    与人为划分的认知结构一致：
    
    场道工程（单位工程）
    ├── 土方工程（分部）
    │   ├── 土方开挖（分项）
    │   ├── 土方填筑（分项）
    │   ├── 特殊土处理（分项）
    │   └── 边坡处理（分项）
    ├── 基层工程（分部）
    │   └── ...
    ...
    """
    tree: Dict[str, Any] = {}
    for prof_code, prof_info in SUBDIVISION_HIERARCHY.items():
        prof_node: Dict[str, Any] = {
            "label": prof_info["label"],
            "spec": prof_info.get("spec", ""),
            "sub_divisions": {},
        }
        for sub_key, sub_info in prof_info["sub_items"].items():
            sub_node: Dict[str, Any] = {
                "label": sub_info["label"],
                "items": [],
            }
            for item in sub_info["items"]:
                sub_node["items"].append({
                    "code": item["code"],
                    "label": item["label"],
                })
            prof_node["sub_divisions"][sub_key] = sub_node
        tree[prof_code] = prof_node
    return tree