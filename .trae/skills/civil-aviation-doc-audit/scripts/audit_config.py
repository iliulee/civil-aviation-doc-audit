def match_subdivision(
    professional: str,
    keywords: List[str],
) -> Optional[str]:
    """
    根据专业和关键词列表，匹配到最合适的分部分项。
    返回分部分项 code（如 "01-03"），未匹配返回 None。
    
    Args:
        professional: 专业代码，如 "01_场道工程"
        keywords: 从文件名/内容中提取的关键词
    """
    hierarchy = SUBDIVISION_HIERARCHY.get(professional)
    if not hierarchy:
        return None
    
    # 将关键词列表合并为一个字符串便于匹配
    keyword_text = " ".join(keywords).lower()
    
    best_match = None
    best_score = 0
    
    for sub_key, sub_info in hierarchy["sub_items"].items():
        for item in sub_info["items"]:
            match_count = sum(
                1 for kw in item["keywords"]
                if kw.lower() in keyword_text
            )
            if match_count > best_score:
                best_score = match_count
                best_match = item["code"]
    
    return best_match


def assign_subdivision_to_document(
    professional: str,
    doc_type: str,
    subcategory: str = "",
    extra_keywords: Optional[List[str]] = None,
) -> Optional[str]:
    """
    将一份文档分配到最匹配的分部分项 code。
    分配策略（按优先级）：
      1. doc_type 精确匹配 DOC_TYPE_TO_SUBDIVISION
      2. subcategory 模糊匹配 DOC_TYPE_TO_SUBDIVISION
      3. 关键词匹配 SUBDIVISION_HIERARCHY
      4. 匹配不到则返回 None（归入"未分类"）
    
    这个分配逻辑与人的判断习惯一致：
    - 人看到"碎石桩施工记录"自然归入"特殊土处理"
    - 人看到"混凝土面层检验批"自然归入"水泥混凝土面层"
    
    Args:
        professional: 专业代码，如 "01_场道工程"
        doc_type: 资料类型，如 "碎石桩施工记录"
        subcategory: 子分类，如 "施工记录"
        extra_keywords: 从文件内容中提取的额外关键词
    
    Returns:
        分部分项 code，如 "01-03"，未匹配返回 None
    """
    # 策略 1：doc_type 精确匹配
    if doc_type in DOC_TYPE_TO_SUBDIVISION:
        return DOC_TYPE_TO_SUBDIVISION[doc_type]
    
    # 策略 2：子字符串匹配
    for key, code in DOC_TYPE_TO_SUBDIVISION.items():
        if key in doc_type or key in subcategory:
            return code
    
    # 策略 3：关键词匹配
    keywords = [doc_type, subcategory]
    if extra_keywords:
        keywords.extend(extra_keywords)
    kw_match = match_subdivision(professional, keywords)
    if kw_match:
        return kw_match
    
    return None


def get_subdivision_info(
    professional: str,
    code: str,
) -> Optional[Dict[str, Any]]:
    """
    获取分部分项的完整信息，包括所属分部。
    
    Returns:
        {
            "code": "01-03",
            "label": "特殊土处理",
            "sub_label": "土方工程",       ← 所属分部
            "sub_key": "01_土方工程",
            "professional": "01_场道工程",
            "professional_label": "场道工程",
            "spec": "MH/T 5078.2-2024",
        }
    """
    hierarchy = SUBDIVISION_HIERARCHY.get(professional)
    if not hierarchy:
        return None
    
    for sub_key, sub_info in hierarchy["sub_items"].items():
        for item in sub_info["items"]:
            if item["code"] == code:
                return {
                    "code": code,
                    "label": item["label"],
                    "sub_label": sub_info["label"],
                    "sub_key": sub_key,
                    "professional": professional,
                    "professional_label": hierarchy["label"],
                    "spec": hierarchy.get("spec", ""),
                }
    return None


def get_all_subdivision_codes(professional: str) -> List[str]:
    """获取某专业下所有分项工程 code 列表。"""
    hierarchy = SUBDIVISION_HIERARCHY.get(professional)
    if not hierarchy:
        return []
    codes = []
    for sub_info in hierarchy["sub_items"].values():
        for item in sub_info["items"]:
            codes.append(item["code"])
    return codes


def get_subdivision_label(professional: str, code: str) -> Optional[str]:
    """根据 code 获取分项工程中文标签。"""
    info = get_subdivision_info(professional, code)
    if info:
        return f"{info['label']}（{code}）"
    return None


def get_subdivision_groups(
    professional: str,
    assigned_codes: List[str],
) -> List[Dict[str, Any]]:
    """
    将已分配的分项工程 code 列表按分部工程分组。
    用于多 Agent 拆分——每个 Agent 处理一个分部工程。
    
    Returns:
        [{"sub_label": "土方工程", "codes": ["01-01", "01-02", ...], "files": [...]}]
    """
    hierarchy = SUBDIVISION_HIERARCHY.get(professional)
    if not hierarchy:
        return []
    
    groups = []
    for sub_key, sub_info in hierarchy["sub_items"].items():
        sub_codes = [item["code"] for item in sub_info["items"]]
        matched = [c for c in assigned_codes if c in sub_codes]
        if matched:
            groups.append({
                "sub_label": sub_info["label"],
                "sub_key": sub_key,
                "codes": matched,
                "files": [],  # 待填充
            })
    return groups


def group_documents_for_audit(
    documents: List[Dict[str, Any]],
    force_split_by_item: bool = False,
    split_by: str = "sub",
) -> List[Dict[str, Any]]:
    """
    将文档列表按分部分项分组，生成多 Agent 并行审核的任务包。
    这是 Phase 5 多 Agent 拆分的核心函数。
    
    分组策略（与人为划分一致）：
      - split_by="professional": 按专业（单位工程）分组，每个专业一个任务
      - split_by="sub"（默认）: 先按专业再按分部工程分组；大分部自动拆分到分项
      - split_by="item" 或 force_split_by_item=True: 强制按分项工程拆分
    
    每个任务包包含：
      - task_id: 任务标识
      - professional: 专业
      - sub_label: 分部工程名称
      - item_label: 分项工程名称（如果已拆分到分项）
      - subdivision_code: 分部分项 code
      - documents: 该分部分项下的文档列表
      - checklist_ids: 该分部分项的审核检查清单 ID 列表
      - logic_check_ids: 需要执行的逻辑一致性检查 ID 列表
    
    Args:
        documents: 文档列表，每个文档需含 professional、subdivision_code 字段
        force_split_by_item: 是否强制按分项工程拆分（默认仅大分部拆分）
        split_by: 拆分粒度，professional/sub/item
    
    Returns:
        任务包列表，按层级排序
    """
    # 第一步：按专业分组
    by_professional: Dict[str, List[Dict[str, Any]]] = {}
    unassigned: List[Dict[str, Any]] = []
    
    for doc in documents:
        code = doc.get("subdivision_code")
        prof = doc.get("professional", "")
        if code and prof:
            by_professional.setdefault(prof, []).append(doc)
        else:
            unassigned.append(doc)
    
    tasks: List[Dict[str, Any]] = []
    task_counter = 0
    
    for prof, docs in by_professional.items():
        # professional 粒度：每个专业一个任务
        if split_by == "professional":
            all_codes = list(set(d.get("subdivision_code", "") for d in docs if d.get("subdivision_code")))
            all_checklist_ids: List[str] = []
            for c in all_codes:
                all_checklist_ids.extend(SUBDIVISION_CHECKLIST_MAP.get(c, []))
            all_checklist_ids = list(dict.fromkeys(all_checklist_ids))
            
            prof_info = get_subdivision_info(prof, all_codes[0]) if all_codes else None
            prof_label = prof_info["professional_label"] if prof_info else prof
            
            task_counter += 1
            tasks.append({
                "task_id": f"TASK-{task_counter:03d}",
                "professional": prof,
                "professional_label": prof_label,
                "sub_label": f"{prof_label}（全部）",
                "sub_key": prof,
                "item_label": None,
                "subdivision_code": None,
                "subdivision_codes": all_codes,
                "documents": docs,
                "checklist_ids": all_checklist_ids,
                "logic_check_ids": [f"L-{i:02d}" for i in range(1, 11)],
                "doc_count": len(docs),
            })
            continue
        
        # 第二步：按分部工程分组
        by_sub: Dict[str, List[Dict[str, Any]]] = {}
        for doc in docs:
            code = doc.get("subdivision_code", "")
            info = get_subdivision_info(prof, code)
            sub_key = info["sub_key"] if info else "未分类"
            by_sub.setdefault(sub_key, []).append(doc)
        
        # 第三步：决定是否拆分到分项
        for sub_key, sub_docs in by_sub.items():
            sub_info = next(
                (info for doc in sub_docs 
                 for info in [get_subdivision_info(prof, doc.get("subdivision_code", ""))]
                 if info),
                None
            )
            sub_label = sub_info["sub_label"] if sub_info else sub_key
            
            if len(sub_docs) > 10 or force_split_by_item or split_by == "item":
                # 按分项工程拆分
                by_item: Dict[str, List[Dict[str, Any]]] = {}
                for doc in sub_docs:
                    code = doc.get("subdivision_code", "")
                    by_item.setdefault(code, []).append(doc)
                
                for code, item_docs in by_item.items():
                    info = get_subdivision_info(prof, code)
                    task_counter += 1
                    tasks.append({
                        "task_id": f"TASK-{task_counter:03d}",
                        "professional": prof,
                        "professional_label": info["professional_label"] if info else prof,
                        "sub_label": sub_label,
                        "sub_key": sub_key,
                        "item_label": info["label"] if info else code,
                        "subdivision_code": code,
                        "documents": item_docs,
                        "checklist_ids": SUBDIVISION_CHECKLIST_MAP.get(code, []),
                        "logic_check_ids": [f"L-{i:02d}" for i in range(1, 11)],
                        "doc_count": len(item_docs),
                    })
            else:
                # 按分部工程为一个任务
                codes = list(set(d.get("subdivision_code", "") for d in sub_docs))
                all_checklist_ids: List[str] = []
                for c in codes:
                    all_checklist_ids.extend(SUBDIVISION_CHECKLIST_MAP.get(c, []))
                # 去重
                all_checklist_ids = list(dict.fromkeys(all_checklist_ids))
                
                task_counter += 1
                tasks.append({
                    "task_id": f"TASK-{task_counter:03d}",
                    "professional": prof,
                    "professional_label": sub_info["professional_label"] if sub_info else prof,
                    "sub_label": sub_label,
                    "sub_key": sub_key,
                    "item_label": None,  # 未拆分到分项
                    "subdivision_code": None,  # 分部级任务，包含多个分项
                    "subdivision_codes": codes,
                    "documents": sub_docs,
                    "checklist_ids": all_checklist_ids,
                    "logic_check_ids": [f"L-{i:02d}" for i in range(1, 11)],
                    "doc_count": len(sub_docs),
                })
    
    # 未分类文档
    if unassigned:
        task_counter += 1
        tasks.append({
            "task_id": f"TASK-{task_counter:03d}",
            "professional": "未分类",
            "professional_label": "未分类",
            "sub_label": "未分类",
            "sub_key": "未分类",
            "item_label": None,
            "subdivision_code": None,
            "documents": unassigned,
            "checklist_ids": [c["id"] for c in GENERAL_CHECKLIST],
            "logic_check_ids": [f"L-{i:02d}" for i in range(1, 11)],
            "doc_count": len(unassigned),
        })
    
    return tasks


def get_checklist_for_subdivision(
    professional: str,
    code: str,
) -> List[Dict[str, Any]]:
    """
    获取某分部分项的审核检查清单。
    优先从 SUBDIVISION_CHECKLIST_MAP 取，回退到通用清单。
    """
    checklist_ids = SUBDIVISION_CHECKLIST_MAP.get(code, [])
    if not checklist_ids:
        return get_checklist_for_professional(professional)
    
    all_checklists = get_checklist_for_professional(professional)
    id_to_checklist = {c["id"]: c for c in all_checklists}
    
    result = []
    for cid in checklist_ids:
        if cid in id_to_checklist:
            result.append(id_to_checklist[cid])
    return result


